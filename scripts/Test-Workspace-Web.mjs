import {readFile} from 'node:fs/promises';
import {stripTypeScriptTypes} from 'node:module';
import assert from 'node:assert/strict';
globalThis.document={documentElement:{dataset:{}}};
globalThis.localStorage={getItem(){return null}};
const source=await readFile(new URL('../web/layout.ts',import.meta.url),'utf8');
const mod=await import('data:text/javascript;base64,'+Buffer.from(stripTypeScriptTypes(source,{mode:'transform'})+'\nexport {groupWorkspaceTasks};').toString('base64'));
const task=(id,env,workspace,updated,pinned=false)=>({id,environment:env,workspace,updated,pinned});
const windows={id:'win',type:'windows',name:'电脑'};
const wsl={id:'wsl',type:'wsl',name:'电脑',distro:'Ubuntu',user:'dev'};
const ssh={id:'ssh',type:'ssh',name:'电脑',host:'192.168.50.10',user:'root'};
const items=[task('a',windows,'C:\\work',1),task('b',wsl,'/work',2),task('c',ssh,'/work',3),task('d',windows,'C:\\work',4,true),task('e',{...ssh,host:'192.168.50.11'},'/work',5)];
const original=items.map(t=>t.id),groups=mod.groupWorkspaceTasks(items);
assert.equal(groups.length,4,'Same folder name on different execution hosts must not be merged');
assert.deepEqual(groups[0].tasks.map(t=>t.id),['d','a'],'Pinned task keeps its workspace first');
assert.equal(groups[0].name,'work');assert.equal(groups[1].environment,'电脑');
assert.deepEqual(items.map(t=>t.id),original,'Grouping must not reorder the task store');
assert.equal(mod.groupWorkspaceTasks([task('root',wsl,'/',1)])[0].name,'/');
console.log('PASS: workspace grouping isolates hosts/users, keeps pin/order and original data.');
