import {readFile} from 'node:fs/promises';
import {stripTypeScriptTypes} from 'node:module';
import {createContext,runInContext} from 'node:vm';
import assert from 'node:assert/strict';

const sticky=await readFile(new URL('../web/sticky.ts',import.meta.url),'utf8');
const css=await readFile(new URL('../web/workbench.css',import.meta.url),'utf8');
const nodes=new Map();
const node=id=>{
 if(!nodes.has(id))nodes.set(id,{dataset:{},attributes:{},textContent:'',innerHTML:'',value:'',classList:{add(){}},setAttribute(key,value){this.attributes[key]=value},insertAdjacentHTML(){},querySelectorAll(){return []}});
 return nodes.get(id);
};
const ctx=createContext({element:node,button:node,input:node,localStorage:{getItem(){return null},setItem(){}},authenticated:false,stickyLoading:false,stickyRequest:0,stickyItems:[],stickyScope:'all',stickyFilter:'open',stickyLast:'',chosen:'task-1',scratchStatus:item=>item.status,scratchCardHTML:item=>'<article>'+item.id+'</article>',notify(){},editScratch(){},console});
const from=sticky.indexOf('function installStickyBoard('),to=sticky.indexOf('setInterval(',from);
assert(from>=0&&to>from);
runInContext(stripTypeScriptTypes(sticky.slice(from,to),{mode:'transform'}),ctx);
ctx.installStickyBoard();ctx.renderStickyBoard();
assert.equal(node('sticky-board').dataset.empty,'true');
assert.equal(node('sticky-expand').attributes['aria-expanded'],'false');
assert.equal(node('sticky-expand').textContent,'展开');
node('sticky-expand').onclick();
assert.equal(node('sticky-board').dataset.mobileExpanded,'true');
assert.equal(node('sticky-expand').attributes['aria-expanded'],'true');
ctx.renderStickyBoard();
assert.equal(node('sticky-expand').attributes['aria-expanded'],'true','polling an unchanged empty list preserves explicit expansion');
node('sticky-expand').onclick();
ctx.stickyItems=[{id:'one',task_id:'task-1',status:'open'}];ctx.renderStickyBoard();
assert.equal(node('sticky-board').dataset.empty,'false','existing notes are never automatically collapsed');
assert.equal(node('sticky-expand').attributes['aria-expanded'],'true');
assert.match(node('sticky-list').innerHTML,/one/);
ctx.stickyFilter='done';ctx.renderStickyBoard();
assert.equal(node('sticky-board').dataset.empty,'true','empty filtered lists retain an explicit expand/filter entry');
assert.equal(node('sticky-count').textContent,'1 项未完成');
ctx.stickyItems=[];ctx.authenticated=true;ctx.api=async()=>{throw new Error('synthetic read failure')};
await ctx.loadStickyBoard();
assert.equal(node('sticky-board').dataset.empty,'false','a loading error cannot be hidden in the collapsed empty list');
assert.equal(node('sticky-list').textContent,'synthetic read failure');

const media=css.lastIndexOf('@media(max-width:760px){');
const mobile=css.slice(media),desktop=css.slice(0,media);
assert(!desktop.includes('#sticky-board[data-empty="true"]'),'compact board rules must not affect desktop docking');
assert.match(desktop,/#sticky-expand\{display:none\}/);
assert.match(sticky,/aria-controls="sticky-list sticky-filter sticky-scope"/);
assert.match(mobile,/#sticky-board\[data-empty="true"\]\{height:auto;min-height:0;/,'saved dock height cannot reserve empty phone space');
for(const id of ['sticky-list','sticky-filter','sticky-scope'])assert(mobile.includes('#sticky-board[data-empty="true"]:not([data-mobile-expanded="true"]) #'+id));
assert(!mobile.includes(':not([data-mobile-expanded="true"]) #sticky-new'),'new note remains directly accessible');
assert.match(mobile,/#sticky-board>header button,#sticky-board>header select\{min-height:44px;min-width:44px\}/);
assert.match(mobile,/\.composer-tools\{display:grid;grid-template-columns:auto auto minmax\(0,1fr\) 44px;/);
assert.match(mobile,/\.composer-tools button,\.composer-tools select\{[^}]*min-height:44px/);
assert.match(mobile,/\.composer-tools \.mode-engine-hint\{grid-column:1 \/ -1\}/,'engine restrictions remain visible on their own row');
assert.match(mobile,/\.composer-bottom\{display:grid;grid-template-columns:minmax\(0,1fr\) auto;/,'model and send share a row');
assert.match(mobile,/\.composer-bottom button\{min-height:44px;min-width:44px\}/);
assert.match(mobile,/#chat-column \.composer textarea\{min-height:56px;max-height:120px;overflow-y:auto\}/,'long drafts remain scrollable');
assert(!mobile.includes('.session-banner{display:none'),'do not conceal session boundaries');
console.log('PASS: phone empty-note expand/filter state, visible failures, 44px controls and compact composer; desktop rules preserved. Browser geometry is checked separately.');
